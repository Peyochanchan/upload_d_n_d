# frozen_string_literal: true

require "rails/generators"
require "rails/generators/base"

require "rails/generators/active_record"

module UploadDND
  module Generators
    class InstallGenerator < Rails::Generators::Base
      include Rails::Generators::Migration

      source_root File.expand_path("templates", __dir__)

      def self.next_migration_number(dirname)
        Time.now.utc.strftime("%Y%m%d%H%M%S")
      end

      desc "Installe UploadDND dans votre application Rails"

      def check_dependencies
        say "Vérification des dépendances...", :green
      end

      def add_view_component_gem
        return if gem_installed?("view_component")

        say "Ajout de view_component au Gemfile...", :yellow
        gem "view_component", "~> 3.0"

        say "N'oubliez pas de lancer 'bundle install'", :green
      end

      def add_stimulus_rails
        return if gem_installed?("stimulus-rails")

        say "Ajout de stimulus-rails au Gemfile...", :yellow
        gem "stimulus-rails"

        say "N'oubliez pas de lancer 'bundle install' puis 'rails stimulus:install'", :green
      end

      def copy_concerns
        say "Installation des concerns...", :green

        template "concerns/uploadable.rb",
                 "app/models/concerns/upload_d_n_d/uploadable.rb"

        template "concerns/controllers_uploadable.rb",
                 "app/controllers/concerns/upload_d_n_d/controllers/uploadable.rb"

        template "concerns/upload_authorization.rb",
                 "app/controllers/concerns/upload_d_n_d/upload_authorization.rb"
      end

      def copy_helpers
        say "Installation des helpers...", :green

        copy_file "helpers/upload_helper.rb",
                 "app/helpers/upload_d_n_d/upload_helper.rb"
      end

      def copy_validator
        if File.exist?("app/validators/file_validator.rb")
          say "FileValidator existe déjà, on ne le remplace pas", :yellow
        else
          if yes?("Voulez-vous installer le FileValidator recommandé ? (y/n)")
            say "Installation du FileValidator...", :green
            template "validators/file_validator.rb",
                     "app/validators/file_validator.rb"
          end
        end
      end

      def install_stimulus_controller
        say "Installation du contrôleur Stimulus...", :green

        copy_file File.expand_path("../../../app/javascript/upload_d_n_d/controllers/uploads_controller.js", __dir__),
                  "app/javascript/controllers/upload_d_n_d/uploads_controller.js"

        copy_file File.expand_path("../../../app/javascript/upload_d_n_d/controllers/preview_controller.js", __dir__),
                  "app/javascript/controllers/upload_d_n_d/preview_controller.js"
      end

      def register_stimulus_controller
        manifest_path = "app/javascript/controllers/index.js"

        if File.exist?(manifest_path)
          manifest_content = File.read(manifest_path)

          if manifest_content.include?("stimulus:manifest:update") || manifest_content.include?("auto-generated by")
            say "Manifest Stimulus auto-généré détecté.", :green
            say "Je ne modifie pas #{manifest_path} (il serait écrasé).", :yellow
            say "Lancez plutôt :", :yellow
            say "  bin/rails stimulus:manifest:update", :cyan

            if File.exist?("bin/rails") && yes?("Voulez-vous lancer 'bin/rails stimulus:manifest:update' maintenant ? (y/n)")
              rails_command "stimulus:manifest:update"
            end
          else
            say "Manifest Stimulus détecté mais non reconnu comme auto-généré.", :yellow
            say "Par prudence, je ne le modifie pas automatiquement.", :yellow
            say "Enregistrez manuellement les controllers UploadDND (uploads + preview) ou utilisez stimulus:manifest:update si applicable.", :yellow
          end
        else
          say "⚠ Manifest Stimulus non trouvé (app/javascript/controllers/index.js)", :yellow
          say "Si vous utilisez Stimulus, enregistrez manuellement le contrôleur :", :yellow
          say ""
          say "  import UploadDNDUploadsController from \"./upload_d_n_d/uploads_controller\"", :cyan
          say "  application.register(\"upload-d-n-d--uploads\", UploadDNDUploadsController)", :cyan
          say "  import UploadDNDPreviewController from \"./upload_d_n_d/preview_controller\"", :cyan
          say "  application.register(\"upload-d-n-d--preview\", UploadDNDPreviewController)", :cyan
          say ""
        end
      end

      def create_migration_file
        say "Création de la migration pour TemporaryAttachment...", :green

        migration_template "migrations/create_upload_d_n_d_temporary_attachments.rb",
                           "db/migrate/create_upload_d_n_d_temporary_attachments.rb"
      end

      def add_routes
        say "Ajout des routes...", :green

        route_content = <<~RUBY

          # Routes UploadDND
          mount UploadDND::Engine => "/upload_d_n_d"
        RUBY

        route route_content
      end

      def create_initializer
        say "Création du fichier de configuration...", :green

        template "initializers/upload_d_n_d.rb",
                 "config/initializers/upload_d_n_d.rb"
      end

      def copy_views
        # Important: on NE copie PAS les vues dans l'app hôte.
        # Elles sont servies directement depuis la gem (ex: _files_list / _temp_files_list),
        # pour éviter les overrides involontaires et garder un comportement cohérent.
        say "Vues UploadDND: servies directement depuis la gem (aucune vue copiée dans l'app).", :green
      end

      def copy_styles
        say "Installation des styles CSS...", :green

        copy_file File.expand_path("../../../app/assets/stylesheets/upload_d_n_d/application.css", __dir__),
                 "app/assets/stylesheets/upload_d_n_d.css"
      end

      def add_css_import
        # Non-invasif: on ne modifie pas automatiquement les fichiers CSS/layout de l'app hôte.
        say ""
        say "🧩 Styles UploadDND", :yellow
        say "Le fichier a été copié ici : app/assets/stylesheets/upload_d_n_d.css", :cyan
        say ""
        say "Choisissez UNE des options suivantes (selon votre setup) :", :yellow
        say ""
        say "Option A — Import dans votre stylesheet principal (Sprockets / CSS classique) :", :cyan
        say "  @import 'upload_d_n_d.css';", :cyan
        say "  (⚠️ Ne pas ajouter dans application.tailwind.css : préférez l'option B)", :yellow
        say ""
        say "Option B — Link tag dans votre layout (Tailwind / PostCSS / autres pipelines) :", :cyan
        say "  <%= stylesheet_link_tag 'upload_d_n_d', media: 'all' %>", :cyan
        say ""
      end

      def copy_component
        say "Installation du ViewComponent...", :green

        directory File.expand_path("../../../app/components/upload_d_n_d", __dir__),
                 "app/components/upload_d_n_d"
      end

      def generate_policy_if_pundit
        if defined?(Pundit) || File.read("Gemfile").include?("pundit")
          say "Pundit détecté, génération de la policy...", :green

          if yes?("Voulez-vous générer la policy Pundit pour UploadDND ? (y/n)")
            generate "upload_d_n_d:policy"
          end
        end
      end

      def create_version_file
        say "Création du fichier de version...", :green

        require_relative "../../upload_d_n_d/version_tracker"
        UploadDND::VersionTracker.write_version!

        say "✓ Version #{UploadDND::VERSION} enregistrée", :green
      end

      def show_readme
        readme "POST_INSTALL" if File.exist?(source_paths.first + "/POST_INSTALL")
      end

      private

      def gem_installed?(gem_name)
        File.read("Gemfile").include?(gem_name)
      rescue
        false
      end
    end
  end
end
